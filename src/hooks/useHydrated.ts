"use client";

import { useSyncExternalStore } from "react";

/**
 * «Мы уже в браузере» — без setState в эффекте и без расхождения гидратации.
 *
 * Зачем: страница отдаётся как статический HTML, собранный в момент деплоя.
 * Всё, что зависит от текущего времени (список дат записи), нельзя считать
 * во время серверного рендера: на следующий день после сборки гость увидел бы
 * вчерашние числа, а React ругался бы на несовпадение разметки.
 *
 * Реализация через useSyncExternalStore, а не useState + useEffect:
 *  — на сервере и в первом клиентском рендере честно возвращает false,
 *    поэтому разметка совпадает и предупреждения нет;
 *  — после гидратации React сам перерисует подписчиков со значением true,
 *    без каскадного ререндера из эффекта.
 */
const subscribe = () => () => {};

export function useHydrated(): boolean {
  return useSyncExternalStore(
    subscribe,
    () => true,
    () => false,
  );
}

export default useHydrated;
