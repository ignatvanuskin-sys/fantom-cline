/** Блик/мерцание отдельных точек — «битые» пиксели табло. */
export default function DotMatrix({
  text,
  className = "",
  dot = 3,
  gap = 1,
  /** Процент «мёртвых» точек. */
  deadPct = 14,
  color = "#b8121a",
}: {
  text: string;
  className?: string;
  dot?: number;
  gap?: number;
  deadPct?: number;
  color?: string;
}) {
  const [dead, setDead] = useState<Set<number>>(() => new Set());
  const seeded = useRef(false);

  useEffect(() => {
    // Мёртвые точки фиксируем один раз: иначе на каждом ререндере
    // весь табло дёргалось бы
    if (seeded.current) return;
    seeded.current = true;
    const set = new Set<number>();
    for (let i = 0; i < 400; i++) {
      if (Math.random() * 100 < deadPct) set.add(i);
    }
    setDead(set);
  }, [deadPct]);

  const chars = text.toUpperCase().split("");
  // Ширина в «пикселях»: 5 на символ + 1 пробел между символами
  const cols = chars.length * 6 - 1;
  const rows = 7;

  const cells: boolean[] = [];
  chars.forEach((ch, ci) => {
    const glyph = GLYPHS[ch] ?? GLYPHS["?"];
    for (let r = 0; r < rows; r++) {
      const line = glyph[r];
      for (let c = 0; c < 5; c++) {
        cells.push(line[c] === "1");
        if (c === 4 && ci < chars.length - 1) cells.push(false); // отбивка
      }
    }
  });

  return (
    <svg
      viewBox={`0 0 ${cols} ${rows}`}
      className={className}
      role="img"
      aria-label={text}
      shapeRendering="crispEdges"
    >
      {cells.map((on, i) => {
        const col = i % cols;
        const row = Math.floor(i / cols);
        if (!on) return null;
        // «битая» точка гаснет — табло выглядит старым
        const isDead = dead.has(i);
        return (
          <rect
            key={i}
            x={col * (dot + gap)}
            y={row * (dot + gap)}
            width={dot}
            height={dot}
            fill={color}
            opacity={isDead ? 0.12 : 0.92}
            className={isDead ? undefined : "dot-matrix-dot"}
          />
        );
      })}
    </svg>
  );
}
